use std::path::Path;

fn main() {
    // uxie links `libnitroarc_ffi` dynamically and Cargo places it next to the binaries without
    // an rpath. Add one (same as crates/g4-kernel/build.rs) so the app finds it in target/debug.
    let origin = match std::env::var("CARGO_CFG_TARGET_OS").as_deref() {
        Ok("macos") => Some("@executable_path"),
        Ok("linux") => Some("$ORIGIN"),
        _ => None,
    };
    if let Some(origin) = origin {
        println!("cargo:rustc-link-arg-bins=-Wl,-rpath,{origin}");
    }
    // The rpath `@executable_path/../Frameworks` for the .app bundle (dylib in Contents/Frameworks)
    // is added by tauri-build itself, because `bundle.macOS.frameworks` is set. Adding it here as
    // well only makes the linker warn about a duplicate -rpath (`scripts/check-bundle.sh` asserts it).
    ensure_bundle_placeholders();
    println!("cargo:rerun-if-changed=build.rs");
    // `i18n!` embeds `locales/` at compile time, but rustc does not track the files a macro
    // reads: without this a changed catalog would not recompile the crate.
    println!("cargo:rerun-if-changed=locales");
    let target_os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let target_env = std::env::var("CARGO_CFG_TARGET_ENV").unwrap_or_default();
    if target_os == "windows" && target_env == "msvc" {
        build_for_windows_msvc();
    } else {
        tauri_build::build()
    }
}

/// Windows (MSVC) variant of `tauri_build::build()`: the same, but the application manifest is
/// linked into every target instead of only into the app binaries.
///
/// tauri-build embeds its default manifest (a dependency on Common Controls v6) through its
/// resource file, and cargo links that only into binaries. The unit-test binary of this crate
/// reaches tauri/muda GUI code (the menu rebuild, the mock app of the updater tests), which
/// imports Common-Controls v6 entry points; without the manifest Windows loads comctl32 v5 and
/// the binary dies at load with `STATUS_ENTRYPOINT_NOT_FOUND` before any test runs. tauri's own
/// build script does the same for its tests (`embed_manifest_for_tests`).
///
/// So tauri-build gets no manifest, and `/MANIFEST:EMBED` + `/MANIFESTINPUT` put it into every
/// link target (binaries, tests, the lib's test binary, the cdylib). `windows-app-manifest.xml` is
/// tauri-build's default manifest, unchanged (`src/windows-app-manifest.xml` of tauri-build), so
/// the manifest of the app is the same as before; update it if a tauri-build update changes the
/// default. There is deliberately no `/WX`: a linker warning must not fail the build here.
fn build_for_windows_msvc() {
    let attributes = tauri_build::Attributes::new()
        .windows_attributes(tauri_build::WindowsAttributes::new_without_app_manifest());
    if let Err(error) = tauri_build::try_build(attributes) {
        // Same as `tauri_build::build()`: report and fail the build script.
        eprintln!("tauri-build failed: {error:#}");
        std::process::exit(1);
    }

    // The linker runs from the workspace root, so the path has to be absolute.
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")
        .expect("cargo sets CARGO_MANIFEST_DIR for build scripts");
    let manifest = Path::new(&manifest_dir).join("windows-app-manifest.xml");
    let manifest = manifest
        .to_str()
        .expect("the path of windows-app-manifest.xml is not valid UTF-8");
    println!("cargo:rerun-if-changed={manifest}");
    println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
    println!("cargo:rustc-link-arg=/MANIFESTINPUT:{manifest}");
}

/// `bundle.externalBin` and, on macOS targets, `bundle.macOS.frameworks` make tauri-build require
/// `binaries/apicula-<target triple>` and `binaries/rotom-lsp-<target triple>` (both with `.exe`
/// on Windows) plus `frameworks/libnitroarc_ffi.dylib` (macOS targets only) for every build, also
/// `cargo test`/`clippy`. The files are only real after `scripts/prepare-bundle.sh`; until then
/// empty placeholders keep normal builds working. `find_apicula` and `find_rotom_lsp` ignore an
/// empty file and `scripts/check-bundle.sh` fails on empty files, so a placeholder can never pass
/// as the real thing.
///
/// `licenses/THIRD-PARTY-NOTICES.txt` is the same kind of file: `bundle.resources` ships the whole
/// `licenses/` folder, the notices file in it is generated by `scripts/third-party-notices.sh`
/// (gitignored), so an empty placeholder keeps normal builds working. `check-bundle*.sh` require
/// it to be non-empty and to name nitroarc or the LGPL.
///
/// There is deliberately no placeholder for `windows/nitroarc_ffi.dll`: that resource is only
/// declared in `tauri.bundle.windows.conf.json` (used by `scripts/bundle.sh`), because tauri-build
/// copies every `bundle.resources` entry next to the binary on each build and an empty file would
/// overwrite the real DLL that uxie's build script stages there.
fn ensure_bundle_placeholders() {
    let Ok(triple) = std::env::var("TARGET") else {
        return;
    };
    let target_os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    // tauri-build looks for the sidecars with `.exe` on Windows targets.
    let exe = if target_os == "windows" { ".exe" } else { "" };
    let mut paths = vec![
        format!("binaries/apicula-{triple}{exe}"),
        format!("binaries/rotom-lsp-{triple}{exe}"),
    ];
    // Generated by scripts/third-party-notices.sh; the other files in licenses/ are checked in.
    paths.push("licenses/THIRD-PARTY-NOTICES.txt".to_string());
    // nitroarc stays a separate file: a framework on macOS (see the note above for Windows).
    if target_os == "macos" {
        paths.push("frameworks/libnitroarc_ffi.dylib".to_string());
    }
    for path in paths {
        let path = Path::new(&path);
        if !path.exists() {
            if let Some(dir) = path.parent() {
                let _ = std::fs::create_dir_all(dir);
            }
            let _ = std::fs::write(path, b"");
        }
    }
}
